/** Поиск по набору. Ищем по имени группы — отдельных названий у нас нет. */
export function filterEmoji(query: string): EmojiGroup[] {
  const needle = query.trim().toLowerCase();
  if (!needle) return EMOJI;
  return EMOJI.filter((group) => group.name.includes(needle));
}
